import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import bcrypt from "bcryptjs";
import { app } from "../src/app.js";
import { portalStore } from "../src/config/portalStore.js";
import { closePostgresPool } from "../src/config/postgres.js";
import { createJwtSession } from "../src/services/jwtSession.js";

let server;
let base;
const ids = [];
const unique = randomUUID();
const headers = (token) => ({ "content-type": "application/json", cookie: `school_visit_session=${token}` });
const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aQe0AAAAASUVORK5CYII=";

before(async () => {
  process.env.ADMIN_EMAIL = "admin@example.test";
  process.env.ADMIN_PASSWORD_HASH = bcrypt.hashSync("test-password-123", 4);
  process.env.SESSION_SECRET = "trainer-visit-test-secret-is-long-enough";
  server = app.listen(0);
  await new Promise((resolve) => server.once("listening", resolve));
  base = `http://127.0.0.1:${server.address().port}`;
});
after(async () => {
  for (const [collection, id] of ids.reverse()) await portalStore().collection(collection).doc(id).delete();
  await new Promise((resolve) => server.close(resolve));
  await closePostgresPool();
});

test("trainer adds a school and photo visit; admin sees the report", async () => {
  const adminToken = await createJwtSession({ sub: "admin", role: "admin" });
  const email = `trainer-visits-${unique}@example.test`;
  const created = await fetch(`${base}/api/trainers`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ name: "Test Trainer", email, password: "trainer-password-123" }) });
  assert.equal(created.status, 201);
  const trainer = (await created.json()).trainer;
  ids.push(["trainers", trainer.id]);
  const login = await fetch(`${base}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ identifier: email, password: "trainer-password-123" }) });
  assert.equal(login.status, 200);
  const trainerToken = login.headers.get("set-cookie").split(";")[0].split("=")[1];
  const cityResponse = await fetch(`${base}/api/trainers/locations/cities`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ name: `Trainer City ${unique}` }) });
  assert.equal(cityResponse.status, 201);
  const ownCity = (await cityResponse.json()).city;
  ids.push(["cities", ownCity.id]);
  const repeatedCity = await fetch(`${base}/api/trainers/locations/cities`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ name: ownCity.name.toLowerCase() }) });
  assert.equal((await repeatedCity.json()).city.id, ownCity.id);
  const schoolName = `Test School ${"North ".repeat(25)}`.trim();
  const schoolResponse = await fetch(`${base}/api/trainers/locations/schools`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ cityId: ownCity.id, name: schoolName }) });
  assert.equal(schoolResponse.status, 201);
  const school = (await schoolResponse.json()).school;
  assert.equal(school.name, schoolName);
  ids.push(["schools", school.id]);
  const longNotes = "Detailed visit note. ".repeat(140);
  const visitResponse = await fetch(`${base}/api/trainers/visits`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ cityId: ownCity.id, schoolId: school.id, principalName: "Principal", phone: "1234567890", notes: longNotes, image: png }) });
  assert.equal(visitResponse.status, 201);
  const visit = (await visitResponse.json()).visit;
  ids.push(["trainer_school_details", `${trainer.id}_${school.id}`], ["trainer_visits", visit.id]);
  assert.equal(visit.trainerId, trainer.id);
  assert.equal(visit.image, undefined);
  assert.equal(visit.cityName, ownCity.name);
  assert.equal(visit.areaName, "");
  assert.equal(visit.purpose, undefined);
  assert.equal(visit.notes, longNotes.trim());
  const oversizedPhoto = `data:image/png;base64,${Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), Buffer.alloc(100 * 1024 - 7)]).toString("base64")}`;
  const tooLarge = await fetch(`${base}/api/trainers/visits`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ cityId: ownCity.id, schoolId: school.id, principalName: "Principal", phone: "1234567890", image: oversizedPhoto }) });
  assert.equal(tooLarge.status, 400);
  assert.match((await tooLarge.json()).error, /80 KB/);
  const fakePhoto = await fetch(`${base}/api/trainers/visits`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ cityId: ownCity.id, schoolId: school.id, principalName: "Principal", phone: "1234567890", image: "data:image/png;base64,ZmFrZQ==" }) });
  assert.equal(fakePhoto.status, 400);
  const own = await fetch(`${base}/api/trainers/visits`, { headers: headers(trainerToken) });
  assert.ok((await own.json()).visits.some((item) => item.id === visit.id));
  const admin = await fetch(`${base}/api/trainers/visits?trainerId=${trainer.id}`, { headers: headers(adminToken) });
  assert.ok((await admin.json()).visits.some((item) => item.id === visit.id));
  const photo = await fetch(`${base}/api/trainers/visits/${visit.id}/photo`, { headers: headers(trainerToken) });
  assert.equal(photo.status, 200);
  assert.match(photo.headers.get("content-type"), /image\/png/);
  const schools = await fetch(`${base}/api/trainers/locations/schools?cityId=${ownCity.id}`, { headers: headers(trainerToken) });
  assert.deepEqual((await schools.json()).schools.find((item) => item.id === school.id).visitDetails, { principalName: "Principal", phone: "1234567890" });
  const renamed = await fetch(`${base}/api/trainers/locations/schools/${school.id}`, { method: "PATCH", headers: headers(trainerToken), body: JSON.stringify({ name: `${schoolName} Updated` }) });
  assert.equal(renamed.status, 200);
  const schoolsAfterEdit = await fetch(`${base}/api/trainers/locations/schools?cityId=${ownCity.id}`, { headers: headers(trainerToken) });
  const editedSchool = (await schoolsAfterEdit.json()).schools.find((item) => item.id === school.id);
  assert.equal(editedSchool.name, `${schoolName} Updated`);
  assert.equal(editedSchool.visitDetails.principalName, "Principal");
  const otherEmail = `other-trainer-${unique}@example.test`;
  const otherCreated = await fetch(`${base}/api/trainers`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ name: "Other Trainer", email: otherEmail, password: "trainer-password-123" }) });
  assert.equal(otherCreated.status, 201);
  const otherTrainer = (await otherCreated.json()).trainer;
  ids.push(["trainers", otherTrainer.id]);
  const otherLogin = await fetch(`${base}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ identifier: otherEmail, password: "trainer-password-123" }) });
  const otherToken = otherLogin.headers.get("set-cookie").split(";")[0].split("=")[1];
  const otherVisits = await fetch(`${base}/api/trainers/visits`, { headers: headers(otherToken) });
  assert.ok(!(await otherVisits.json()).visits.some((item) => item.id === visit.id));
  assert.equal((await fetch(`${base}/api/trainers/visits/${visit.id}/photo`, { headers: headers(otherToken) })).status, 404);
  const otherCities = await fetch(`${base}/api/trainers/locations/cities`, { headers: headers(otherToken) });
  assert.ok(!(await otherCities.json()).cities.some((item) => item.id === ownCity.id));
  const otherSchools = await fetch(`${base}/api/trainers/locations/schools?cityId=${ownCity.id}`, { headers: headers(otherToken) });
  assert.ok(!(await otherSchools.json()).schools.some((item) => item.id === school.id));
  const otherEdit = await fetch(`${base}/api/trainers/locations/schools/${school.id}`, { method: "PATCH", headers: headers(otherToken), body: JSON.stringify({ name: "Changed" }) });
  assert.equal(otherEdit.status, 404);
  const otherVisit = await fetch(`${base}/api/trainers/visits`, { method: "POST", headers: headers(otherToken), body: JSON.stringify({ cityId: ownCity.id, schoolId: school.id, principalName: "Other", phone: "1234567890", image: png }) });
  assert.equal(otherVisit.status, 400);
  const today = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Karachi", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
  ids.push(["trainer_attendance", `${otherTrainer.id}_${today}`]);
  const leaveReason = "Long leave explanation. ".repeat(30);
  const leave = await fetch(`${base}/api/trainers/records/attendance`, { method: "POST", headers: headers(otherToken), body: JSON.stringify({ date: today, action: "leave", remarks: leaveReason }) });
  assert.equal(leave.status, 201);
  assert.equal((await leave.json()).record.remarks, leaveReason.trim());
});

test("trainer weekly plan saves every selected day and admin can review it", async () => {
  const adminToken = await createJwtSession({ sub: "admin", role: "admin" });
  const created = await fetch(`${base}/api/trainers`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ name: "Weekly Trainer", email: `weekly-${unique}@example.test`, password: "trainer-password-123" }) });
  assert.equal(created.status, 201);
  const trainer = (await created.json()).trainer;
  ids.push(["trainers", trainer.id], ["trainer_weekly_plans", `${trainer.id}_2026-11-02`], ["trainer_weekly_plans", `${trainer.id}_2026-11-09`], ["trainer_weekly_plans", `${trainer.id}_2026-11-16`]);
  const trainerToken = await createJwtSession({ sub: trainer.id, role: "trainer" });
  const days = ["2026-11-02", "2026-11-03", "2026-11-04"].map((date) => ({ date, area: date === "2026-11-02" ? "North ".repeat(45) : "North", purpose: date === "2026-11-02" ? "Long weekly plan. ".repeat(130) : `Plan for ${date}` }));
  const saved = await fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-11-02", toDate: "2026-11-04", days }) });
  assert.equal(saved.status, 201);
  assert.equal((await saved.json()).record.days[0].purpose, days[0].purpose.trim());
  const duplicate = await fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-11-02", toDate: "2026-11-04", days }) });
  assert.equal(duplicate.status, 409);
  assert.match((await duplicate.json()).error, /already exists/);
  const earlierDays = ["2026-10-26", "2026-10-27"].map((date) => ({ date, area: "North", purpose: "Training" }));
  const earlier = await fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-10-26", toDate: "2026-10-27", days: earlierDays }) });
  assert.equal(earlier.status, 409);
  const weeklyPrefill = await fetch(`${base}/api/trainers/plan-for-date?date=2026-11-03`, { headers: headers(trainerToken) });
  assert.deepEqual(await weeklyPrefill.json(), { source: "weekly", plan: { area: "North", purpose: "Plan for 2026-11-03" } });
  const editedDays = days.map((day) => day.date === "2026-11-03" ? { ...day, area: "Updated Area", purpose: "Updated Purpose" } : day);
  const edited = await fetch(`${base}/api/trainers/records/weekly/2026-11-02`, { method: "PATCH", headers: headers(trainerToken), body: JSON.stringify({ toDate: "2026-11-04", days: editedDays }) });
  assert.equal(edited.status, 200);
  assert.equal((await edited.json()).record.days[1].purpose, "Updated Purpose");
  const editedPrefill = await fetch(`${base}/api/trainers/plan-for-date?date=2026-11-03`, { headers: headers(trainerToken) });
  assert.deepEqual(await editedPrefill.json(), { source: "weekly", plan: { area: "Updated Area", purpose: "Updated Purpose" } });
  const denied = await fetch(`${base}/api/trainers/plan-for-date?date=2026-11-03`, { headers: headers(adminToken) });
  assert.equal(denied.status, 403);
  const deniedEdit = await fetch(`${base}/api/trainers/records/weekly/2026-11-02`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ toDate: "2026-11-04", days }) });
  assert.equal(deniedEdit.status, 403);
  const nextDays = ["2026-11-09", "2026-11-10"].map((date) => ({ date, area: "Next Area", purpose: "Training" }));
  const nextWeek = await fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-11-09", toDate: "2026-11-10", days: nextDays }) });
  assert.equal(nextWeek.status, 201);
  const concurrentPayload = JSON.stringify({ date: "2026-11-16", toDate: "2026-11-17", days: ["2026-11-16", "2026-11-17"].map((date) => ({ date, area: "West", purpose: "Training" })) });
  const concurrent = await Promise.all([0, 1].map(() => fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: concurrentPayload })));
  assert.deepEqual(concurrent.map((item) => item.status).sort(), [201, 409]);
  const savedDailyId = `${trainer.id}_2026-11-03`;
  ids.push(["trainer_daily_plans", savedDailyId]);
  await portalStore().collection("trainer_daily_plans").doc(savedDailyId).set({ trainerId: trainer.id, date: "2026-11-03", area: "Edited Area", purpose: "Edited Purpose" });
  const dailyPrefill = await fetch(`${base}/api/trainers/plan-for-date?date=2026-11-03`, { headers: headers(trainerToken) });
  assert.deepEqual(await dailyPrefill.json(), { source: "daily", plan: { area: "Edited Area", purpose: "Edited Purpose" } });
  const longArea = "South ".repeat(45);
  const longDailyPurpose = "Long daily plan. ".repeat(130);
  ids.push(["trainer_daily_plans", `${trainer.id}_2026-11-04`]);
  const savedDaily = await fetch(`${base}/api/trainers/records/daily`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-11-04", area: longArea, purpose: longDailyPurpose }) });
  assert.equal(savedDaily.status, 201);
  assert.equal((await savedDaily.json()).record.purpose, longDailyPurpose.trim());
  const own = await fetch(`${base}/api/trainers/records/weekly?from=2026-11-03&to=2026-11-03`, { headers: headers(trainerToken) });
  assert.equal((await own.json()).records.find((record) => record.date === "2026-11-02").days.length, 3);
  const admin = await fetch(`${base}/api/trainers/records/weekly?trainerId=${trainer.id}`, { headers: headers(adminToken) });
  assert.equal((await admin.json()).records.find((record) => record.date === "2026-11-02").toDate, "2026-11-04");
  const invalid = await fetch(`${base}/api/trainers/records/weekly`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date: "2026-11-02", toDate: "2026-11-08", days }) });
  assert.equal(invalid.status, 400);
  const today = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Karachi", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
  const attendanceId = `${trainer.id}_${today}`;
  const dailyId = `${trainer.id}_${today}`;
  const visitId = randomUUID();
  ids.push(["trainer_attendance", attendanceId], ["trainer_daily_plans", dailyId], ["trainer_visits", visitId]);
  const unmarkedSummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(trainerToken) });
  assert.equal((await unmarkedSummary.json()).attendanceMarked, false);
  await Promise.all([
    portalStore().collection("trainer_attendance").doc(attendanceId).set({ trainerId: trainer.id, date: today, status: "present", checkInAt: new Date().toISOString() }),
    portalStore().collection("trainer_daily_plans").doc(dailyId).set({ trainerId: trainer.id, date: today, area: "North", purpose: "Training" }),
    portalStore().collection("trainer_visits").doc(visitId).set({ trainerId: trainer.id, date: today })
  ]);
  const ownSummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(trainerToken) });
  assert.equal(ownSummary.status, 200);
  assert.deepEqual((({ attendanceCount, attendanceMarked, dailyPlanCount, visitCount, dailyPlanMarked }) => ({ attendanceCount, attendanceMarked, dailyPlanCount, visitCount, dailyPlanMarked }))(await ownSummary.json()), { attendanceCount: 1, attendanceMarked: true, dailyPlanCount: 1, visitCount: 1, dailyPlanMarked: true });
  const adminSummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(adminToken) });
  assert.equal(adminSummary.status, 200);
  const totals = await adminSummary.json();
  assert.ok(totals.attendanceCount >= 1 && totals.dailyPlanCount >= 1 && totals.visitCount >= 1);
  await portalStore().collection("trainer_attendance").doc(attendanceId).set({ trainerId: trainer.id, date: today, status: "leave", remarks: "Sick" });
  const leaveSummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(trainerToken) });
  assert.equal(leaveSummary.status, 200);
  assert.deepEqual((({ attendanceCount, attendanceMarked }) => ({ attendanceCount, attendanceMarked }))(await leaveSummary.json()), { attendanceCount: 1, attendanceMarked: true });
  const adminLeaveSummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(adminToken) });
  assert.ok((await adminLeaveSummary.json()).attendanceCount >= 1);
});
