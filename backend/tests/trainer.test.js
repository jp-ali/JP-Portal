import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import bcrypt from "bcryptjs";
import { app } from "../src/app.js";
import { createJwtSession } from "../src/services/jwtSession.js";
import { closePostgresPool } from "../src/config/postgres.js";
import { portalStore } from "../src/config/portalStore.js";

let server;
let base;
const unique = randomUUID().slice(0, 8);
const email = `trainer-${unique}@example.test`;
const headers = (token) => ({ "content-type": "application/json", cookie: `school_visit_session=${token}` });
const date = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Karachi", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
const proof = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aQe0AAAAASUVORK5CYII=";

before(async () => {
  process.env.ADMIN_EMAIL = "admin@example.test";
  process.env.ADMIN_PASSWORD_HASH = bcrypt.hashSync("test-password-123", 4);
  process.env.SESSION_SECRET = "trainer-test-session-secret-is-long-enough";
  server = app.listen(0);
  await new Promise((resolve) => server.once("listening", resolve));
  base = `http://127.0.0.1:${server.address().port}`;
});
after(async () => { await new Promise((resolve) => server.close(resolve)); await closePostgresPool(); });

test("admin creates a trainer; trainer signs in and only sees their records", async () => {
  const adminToken = await createJwtSession({ sub: "admin", role: "admin" });
  const create = await fetch(`${base}/api/trainers`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ name: "Test Trainer", email, designation: "Trainer", password: "trainer-password-123" }) });
  assert.equal(create.status, 201);
  const trainer = (await create.json()).trainer;
  assert.equal(trainer.passwordHash, undefined);
  assert.equal(trainer.offlineMode, "trainer");
  const login = await fetch(`${base}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ identifier: email, password: "trainer-password-123" }) });
  assert.equal(login.status, 200);
  assert.equal((await login.clone().json()).user.role, "trainer");
  const trainerToken = login.headers.get("set-cookie").split(";")[0].split("=")[1];
  assert.equal((await login.clone().json()).user.offlineMode, "trainer");
  const disableOffline = await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ offlineMode: "none" }) });
  assert.equal(disableOffline.status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) }).then((response) => response.json())).user.offlineMode, "none");
  assert.equal((await fetch(`${base}/api/trainers/offline-visits`, { method: "POST", headers: headers(trainerToken), body: "{}" })).status, 403);
  assert.equal((await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ offlineMode: "both" }) })).status, 400);
  const enableOffline = await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ offlineMode: "trainer" }) });
  assert.equal(enableOffline.status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) }).then((response) => response.json())).user.offlineMode, "trainer");
  const trainerCard = await fetch(`${base}/api/cards/trainer/me`, { headers: headers(trainerToken) });
  assert.equal(trainerCard.status, 200);
  const card = (await trainerCard.json()).card;
  assert.equal(card.values.name, "Test Trainer");
  assert.equal(card.values.designation, "Trainer");
  assert.equal((await fetch(`${base}/api/cards/me`, { headers: headers(trainerToken) })).status, 403);
  const profilePhoto = "data:image/jpeg;base64,AAAA";
  assert.equal((await fetch(`${base}/api/trainers/me/photo`, { method: "PUT", headers: headers(adminToken), body: JSON.stringify({ photo: profilePhoto }) })).status, 403);
  assert.equal((await fetch(`${base}/api/trainers/me/photo`, { method: "PUT", headers: headers(trainerToken), body: JSON.stringify({ photo: "not an image" }) })).status, 400);
  const uploadPhoto = await fetch(`${base}/api/trainers/me/photo`, { method: "PUT", headers: headers(trainerToken), body: JSON.stringify({ photo: profilePhoto }) });
  assert.equal(uploadPhoto.status, 200);
  assert.equal((await uploadPhoto.json()).profilePhoto, profilePhoto);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) }).then((response) => response.json())).user.profilePhoto, profilePhoto);
  const editTrainer = await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ designation: "Senior Trainer" }) });
  assert.equal(editTrainer.status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) }).then((response) => response.json())).user.profilePhoto, profilePhoto);
  assert.equal((await fetch(`${base}/api/trainers/me/photo`, { method: "DELETE", headers: headers(trainerToken) })).status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) }).then((response) => response.json())).user.profilePhoto, null);
  const weeklyRef = portalStore().collection("trainer_weekly_plans").doc(`${trainer.id}_${date}`);
  await weeklyRef.set({ trainerId: trainer.id, date, days: [{ date, area: "North", purpose: "Training" }] });
  const weeklyOnlySummary = await fetch(`${base}/api/trainers/dashboard-summary`, { headers: headers(trainerToken) });
  assert.equal((await weeklyOnlySummary.json()).dailyPlanCount, 0);
  await weeklyRef.delete();
  assert.equal((await fetch(`${base}/api/trainers`, { headers: headers(trainerToken) })).status, 403);
  assert.equal((await fetch(`${base}/api/data/collections/visits`, { headers: headers(trainerToken) })).status, 403);
  const save = await fetch(`${base}/api/trainers/records/daily`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date, area: "Lahore", purpose: "School training", trainerId: "someone-else" }) });
  assert.equal(save.status, 201);
  assert.equal((await save.json()).record.trainerId, trainer.id);
  const own = await fetch(`${base}/api/trainers/records/daily?trainerId=someone-else`, { headers: headers(trainerToken) });
  assert.equal(own.status, 200);
  assert.ok((await own.json()).records.every((record) => record.trainerId === trainer.id));
  const month = date.slice(0, 7);
  const ownMonth = await fetch(`${base}/api/trainers/attendance/monthly?month=${month}&trainerId=someone-else`, { headers: headers(trainerToken) });
  assert.equal(ownMonth.status, 200);
  assert.deepEqual((await ownMonth.json()).days, []);
  assert.equal((await fetch(`${base}/api/trainers/attendance/monthly-all?month=${month}`, { headers: headers(trainerToken) })).status, 403);
  const allMonths = await fetch(`${base}/api/trainers/attendance/monthly-all?month=${month}`, { headers: headers(adminToken) });
  assert.equal(allMonths.status, 200);
  assert.ok((await allMonths.json()).trainers.some((person) => person.id === trainer.id));
  assert.equal((await fetch(`${base}/api/trainers/attendance/holidays?month=${month}`, { headers: headers(trainerToken) })).status, 200);
  const noProof = await fetch(`${base}/api/trainers/expenses`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date, category: "Travel", amount: 1250.5, description: "School visit transport" }) });
  assert.equal(noProof.status, 400);
  const oversizedProof = `data:image/png;base64,${Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), Buffer.alloc(130 * 1024 - 7)]).toString("base64")}`;
  const tooLargeProof = await fetch(`${base}/api/trainers/expenses`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date, category: "Travel", amount: 1250.5, description: "School visit transport", proof: oversizedProof }) });
  assert.equal(tooLargeProof.status, 400);
  assert.match((await tooLargeProof.json()).error, /65 KB/);
  const noOtherDetail = await fetch(`${base}/api/trainers/expenses`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date, category: "Other", amount: 1250.5, description: "Miscellaneous", proof }) });
  assert.equal(noOtherDetail.status, 400);
  const expense = await fetch(`${base}/api/trainers/expenses`, { method: "POST", headers: headers(trainerToken), body: JSON.stringify({ date, category: "Other", otherCategory: "Printing", amount: 1250.5, description: "School visit transport", proof, trainerId: "someone-else" }) });
  assert.equal(expense.status, 201);
  const createdExpense = (await expense.json()).expense;
  assert.equal(createdExpense.trainerId, trainer.id);
  assert.equal(createdExpense.proof, undefined);
  const expenseList = await fetch(`${base}/api/trainers/expenses`, { headers: headers(trainerToken) });
  assert.equal(expenseList.status, 200);
  assert.ok((await expenseList.json()).expenses.some((item) => item.description === "School visit transport" && item.trainerId === trainer.id && item.proofAvailable));
  const adminExpenseList = await fetch(`${base}/api/trainers/expenses?from=${date}&to=${date}`, { headers: headers(adminToken) });
  assert.ok((await adminExpenseList.json()).expenses.some((item) => item.id === createdExpense.id));
  const savedProof = await fetch(`${base}/api/trainers/expenses/${createdExpense.id}/proof`, { headers: headers(trainerToken) });
  assert.equal((await savedProof.json()).proof, proof);
  const otherTrainer = await fetch(`${base}/api/trainers`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ name: "Second Trainer", email: `second-${unique}@example.test`, password: "trainer-password-123" }) });
  const otherTrainerId = (await otherTrainer.json()).trainer.id;
  const otherToken = await createJwtSession({ sub: otherTrainerId, role: "trainer" });
  assert.equal((await fetch(`${base}/api/trainers/expenses/${createdExpense.id}/proof`, { headers: headers(otherToken) })).status, 404);
  assert.ok(!(await fetch(`${base}/api/trainers/expenses`, { headers: headers(otherToken) }).then((response) => response.json())).expenses.some((item) => item.id === createdExpense.id));
  assert.equal((await fetch(`${base}/api/trainers/expenses`, { method: "POST", headers: headers(adminToken), body: JSON.stringify({ date, category: "Food", amount: 1, paymentMethod: "Cash", description: "test" }) })).status, 403);
  const disable = await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ active: false }) });
  assert.equal(disable.status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) })).status, 401);
  const archive = await fetch(`${base}/api/trainers/${trainer.id}/archive`, { method: "PATCH", headers: headers(adminToken) });
  assert.equal(archive.status, 200);
  assert.equal((await fetch(`${base}/api/trainers`, { headers: headers(adminToken) }).then((response) => response.json())).trainers.some((item) => item.id === trainer.id), false);
  assert.equal((await fetch(`${base}/api/trainers?archived=1`, { headers: headers(adminToken) }).then((response) => response.json())).trainers.some((item) => item.id === trainer.id), true);
  assert.equal((await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ active: true }) })).status, 404);
  const restore = await fetch(`${base}/api/trainers/${trainer.id}/restore`, { method: "PATCH", headers: headers(adminToken) });
  assert.equal(restore.status, 200);
  assert.equal((await restore.json()).trainer.active, false);
  assert.equal((await fetch(`${base}/api/trainers?archived=1`, { headers: headers(adminToken) }).then((response) => response.json())).trainers.some((item) => item.id === trainer.id), false);
  const activate = await fetch(`${base}/api/trainers/${trainer.id}`, { method: "PATCH", headers: headers(adminToken), body: JSON.stringify({ active: true }) });
  assert.equal(activate.status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) })).status, 200);
  assert.equal((await fetch(`${base}/api/trainers/${trainer.id}/archive`, { method: "PATCH", headers: headers(adminToken) })).status, 200);
  assert.equal((await fetch(`${base}/api/auth/me`, { headers: headers(trainerToken) })).status, 401);
  const restoredActive = await fetch(`${base}/api/trainers/${trainer.id}/restore`, { method: "PATCH", headers: headers(adminToken) });
  assert.equal(restoredActive.status, 200);
  assert.equal((await restoredActive.json()).trainer.active, true);
});
