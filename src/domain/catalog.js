const PAKISTAN_CITY_DATA_URL = "https://raw.githubusercontent.com/thewebguy27/cities/main/pk.json";
const normalizeEntityName = (value = "") => String(value).trim().replace(/\s+/g, " ").toLowerCase();
const entitySlug = (value = "") => normalizeEntityName(value)
.normalize("NFKD")
.replace(/[\u0300-\u036f]/g, "")
.replace(/[^a-z0-9]+/g, "-")
.replace(/^-+|-+$/g, "") || "item";
const entityHash = (value = "") => {
let hash = 2166136261;
for (const ch of normalizeEntityName(value)) {
hash ^= ch.codePointAt(0);
hash = Math.imul(hash, 16777619);
}
return (hash >>> 0).toString(36);
};
const makeCityId = (name) => `city-${entitySlug(name)}-${entityHash(name)}`;
const makeAreaId = (cityId, name) => `${cityId}__area-${entitySlug(name)}-${entityHash(name)}`;
const makeSchoolId = (areaId, name) => `${areaId}__school-${entitySlug(name)}-${entityHash(name)}`;

export { PAKISTAN_CITY_CATALOG, ACTION_PLAN_PURPOSES, PAKISTAN_CITY_DATA_URL, normalizeEntityName, entitySlug, entityHash, makeCityId, makeAreaId, makeSchoolId };
